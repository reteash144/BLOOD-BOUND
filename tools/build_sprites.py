#!/usr/bin/env python3
"""Build public/assets/sprites/pathogens.png from art/source/pathogen-sheet.jpeg.

The source art is six pathogens (rows) x five poses (columns) on black:
idle1, idle2, attack, hit, death. Each pose is soft-keyed, centred on its body,
and packed into a uniform cell for Phaser's spritesheet loader.

Run: python3 tools/build_sprites.py
Requirements: pip install pillow numpy scipy
"""
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage as ndi

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "art" / "source" / "pathogen-sheet.jpeg"
OUT = ROOT / "public" / "assets" / "sprites" / "pathogens.png"
METRICS_OUT = ROOT / "js" / "sprites" / "spriteMetrics.js"

# Row order must match PATHOGENS[*].row in js/sprites/spriteConfig.js.
PATHOGEN_ORDER = ["ebola", "sars", "hiv", "rsv", "cmv", "chik"]
POSES = ["idle1", "idle2", "attack", "hit", "death"]

# Crop windows in the 1536x1024 source: y-bands per row, x-edges per column.
ROW_BANDS = [(12, 188), (190, 358), (358, 510), (512, 656), (658, 816), (818, 990)]
COL_EDGES = [258, 500, 745, 995, 1240, 1536]

BG_MAX = 30
KEY_LO, KEY_HI = 12, 70
PAD = 6


def cut_pose(img: np.ndarray):
    """Return (RGBA float array, main-body bbox) for one cropped pose."""
    img = img.astype(np.float32)
    mx = img.max(axis=2)
    fg = mx >= BG_MAX
    fg = ndi.binary_closing(fg, iterations=2)
    solid = ndi.binary_fill_holes(fg)
    core = ndi.binary_erosion(solid, iterations=2)

    soft = np.clip((mx - KEY_LO) / float(KEY_HI - KEY_LO), 0.0, 1.0) ** 0.85
    alpha = np.where(core, 1.0, soft)
    safe = np.maximum(alpha, 1e-3)[..., None]
    rgb = np.where(core[..., None], img, np.clip(img / safe, 0, 255))
    rgba = np.dstack([rgb, alpha * 255.0])

    labels, n = ndi.label(solid)
    if n == 0:
        raise RuntimeError("empty pose in source crop")
    sizes = ndi.sum(solid, labels, range(1, n + 1))
    keep = [i + 1 for i, size in enumerate(sizes) if size >= 0.08 * sizes.max()]
    main = np.isin(labels, keep)
    ys, xs = np.nonzero(main)
    if not len(xs):
        raise RuntimeError("could not determine main body bounds")
    return rgba, (xs.min(), xs.max() + 1, ys.min(), ys.max() + 1)


def main():
    if not SRC.exists():
        sys.exit(f"missing source art: {SRC}")
    sheet = np.asarray(Image.open(SRC).convert("RGB"))
    if sheet.shape[:2] != (1024, 1536):
        sys.exit(f"expected a 1536x1024 source sheet, got {sheet.shape[1]}x{sheet.shape[0]}")

    poses = {}
    for row, (y0, y1) in enumerate(ROW_BANDS):
        for col in range(len(POSES)):
            x0, x1 = COL_EDGES[col], COL_EDGES[col + 1]
            poses[(row, col)] = cut_pose(sheet[y0:y1, x0:x1])

    half_w = half_h = 0
    for rgba, (bx0, bx1, by0, by1) in poses.values():
        cx, cy = (bx0 + bx1) / 2, (by0 + by1) / 2
        ys, xs = np.nonzero(rgba[..., 3] > 8)
        half_w = max(half_w, cx - xs.min(), xs.max() + 1 - cx)
        half_h = max(half_h, cy - ys.min(), ys.max() + 1 - cy)
    cell_w = int(np.ceil(half_w + PAD)) * 2
    cell_h = int(np.ceil(half_h + PAD)) * 2

    out = np.zeros((cell_h * len(PATHOGEN_ORDER), cell_w * len(POSES), 4), np.uint8)
    body = {}
    for row, name in enumerate(PATHOGEN_ORDER):
        for col, pose in enumerate(POSES):
            rgba, (bx0, bx1, by0, by1) = poses[(row, col)]
            dx = int(round(cell_w / 2 - (bx0 + bx1) / 2))
            dy = int(round(cell_h / 2 - (by0 + by1) / 2))
            ys, xs = np.nonzero(rgba[..., 3] > 0)
            for y, x in zip(ys, xs):
                ty, tx = y + dy + row * cell_h, x + dx + col * cell_w
                if row * cell_h <= ty < (row + 1) * cell_h and col * cell_w <= tx < (col + 1) * cell_w:
                    out[ty, tx] = np.clip(rgba[y, x], 0, 255)
            if pose in ("idle1", "idle2"):
                body.setdefault(name, []).append((bx1 - bx0, by1 - by0))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    METRICS_OUT.parent.mkdir(parents=True, exist_ok=True)
    Image.fromarray(out, "RGBA").save(OUT, optimize=True)

    summary = {}
    for name in PATHOGEN_ORDER:
        bw = round(float(np.mean([size[0] for size in body[name]])))
        bh = round(float(np.mean([size[1] for size in body[name]])))
        summary[name] = {"row": PATHOGEN_ORDER.index(name), "bodyHeight": bh, "bodyWidth": bw}

    metrics = {
        "frameWidth": cell_w,
        "frameHeight": cell_h,
        "columns": len(POSES),
        "rows": len(PATHOGEN_ORDER),
        "pathogens": summary,
    }
    METRICS_OUT.write_text(
        "// Generated by tools/build_sprites.py; do not edit by hand.\n"
        + "export const SPRITE_METRICS = " + json.dumps(metrics, indent=2) + ";\n",
        encoding="utf-8",
    )

    print(f"wrote {OUT.relative_to(ROOT)} ({out.shape[1]}x{out.shape[0]} px)")
    print(f"wrote {METRICS_OUT.relative_to(ROOT)}")
    print(f"frameWidth: {cell_w}, frameHeight: {cell_h}, columns: {len(POSES)}, rows: {len(PATHOGEN_ORDER)}")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
